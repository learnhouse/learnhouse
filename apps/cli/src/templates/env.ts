import crypto from 'node:crypto'
import type { SetupConfig } from '../types.js'
import { quoteEnvValue } from '../utils/env-quote.js'
import { publicUrl } from '../services/stack.js'

function generateSecret(): string {
  return crypto.randomBytes(32).toString('base64')
}

/** Secrets an existing install already uses; re-running setup must keep them
 *  (sessions, and the collab server's shared key, depend on them). */
export interface EnvSecrets {
  nextAuthSecret: string
  jwtSecret: string
  collabInternalKey: string
}

export function generateEnvFile(config: SetupConfig, existing: Partial<EnvSecrets> = {}): string {
  const baseUrl = publicUrl(config)
  const domainWithPort = baseUrl.replace(/^https?:\/\//, '')

  const topDomain = config.domain === 'localhost'
    ? 'localhost'
    : config.domain.split('.').slice(-2).join('.')

  const cookieDomain = config.domain === 'localhost'
    ? '.localhost'
    : `.${topDomain}`

  const nextAuthSecret = existing.nextAuthSecret || generateSecret()
  const jwtSecret = existing.jwtSecret || generateSecret()
  const collabInternalKey = existing.collabInternalKey || generateSecret()

  const lines: string[] = [
    '# LearnHouse Environment Variables',
    '# Generated by LearnHouse CLI',
    '',
    '# =============================================================================',
    '# Domain & Hosting Configuration',
    '# =============================================================================',
    '',
    `LEARNHOUSE_DOMAIN=${domainWithPort}`,
    `HTTP_PORT=${config.httpPort}`,
    '',
    '# =============================================================================',
    '# Frontend Environment Variables (NEXT_PUBLIC_*)',
    '# =============================================================================',
    '',
    `NEXT_PUBLIC_LEARNHOUSE_API_URL=${baseUrl}/api/v1/`,
    `NEXT_PUBLIC_LEARNHOUSE_BACKEND_URL=${baseUrl}/`,
    `NEXT_PUBLIC_LEARNHOUSE_DOMAIN=${domainWithPort}`,
    `NEXT_PUBLIC_LEARNHOUSE_TOP_DOMAIN=${topDomain}`,
    'NEXT_PUBLIC_LEARNHOUSE_MULTI_ORG=False',
    `NEXT_PUBLIC_LEARNHOUSE_DEFAULT_ORG=${config.orgSlug || 'default'}`,
    `NEXT_PUBLIC_LEARNHOUSE_HTTPS=${config.useHttps ? 'True' : 'False'}`,
  ]

  lines.push(
    '',
    '# =============================================================================',
    '# NextAuth Configuration',
    '# =============================================================================',
    '',
    `NEXTAUTH_URL=${baseUrl}`,
    `NEXTAUTH_SECRET=${nextAuthSecret}`,
  )

  if (config.googleOAuthEnabled && config.googleClientId && config.googleClientSecret) {
    lines.push(
      `LEARNHOUSE_GOOGLE_CLIENT_ID=${quoteEnvValue(config.googleClientId!)}`,
      `LEARNHOUSE_GOOGLE_CLIENT_SECRET=${quoteEnvValue(config.googleClientSecret!)}`,
    )
  }

  lines.push(
    '',
    '# =============================================================================',
    '# Backend Configuration',
    '# =============================================================================',
    '',
    `LEARNHOUSE_SQL_CONNECTION_STRING=${config.useExternalDb
      ? quoteEnvValue(config.externalDbConnectionString!)
      : `postgresql://learnhouse:${config.dbPassword}@db:5432/learnhouse`}`,
    `LEARNHOUSE_REDIS_CONNECTION_STRING=${config.useExternalRedis
      ? quoteEnvValue(config.externalRedisConnectionString!)
      : 'redis://redis:6379/learnhouse'}`,
    `LEARNHOUSE_COOKIE_DOMAIN=${cookieDomain}`,
    'LEARNHOUSE_PORT=9000',
    '',
    '# =============================================================================',
    '# Security',
    '# =============================================================================',
    '',
    `LEARNHOUSE_AUTH_JWT_SECRET_KEY=${jwtSecret}`,
    `LEARNHOUSE_INITIAL_ADMIN_EMAIL=${quoteEnvValue(config.adminEmail)}`,
    `LEARNHOUSE_INITIAL_ADMIN_PASSWORD=${quoteEnvValue(config.adminPassword)}`,
    `LEARNHOUSE_INITIAL_ORG_NAME=${quoteEnvValue(config.orgName || 'Default Organization')}`,
    `LEARNHOUSE_INITIAL_ORG_SLUG=${quoteEnvValue(config.orgSlug || 'default')}`,
    '',
    '# =============================================================================',
    '# Collaboration Server',
    '# =============================================================================',
    '',
    `COLLAB_INTERNAL_KEY=${collabInternalKey}`,
    `LEARNHOUSE_REDIS_URL=${config.useExternalRedis
      ? quoteEnvValue(config.externalRedisConnectionString!)
      : 'redis://redis:6379'}`,
    `NEXT_PUBLIC_COLLAB_URL=${config.useHttps ? 'wss' : 'ws'}://${domainWithPort}/collab`,
    '',
    '# =============================================================================',
    '# General Settings',
    '# =============================================================================',
    '',
    'LEARNHOUSE_DEVELOPMENT_MODE=False',
    'LEARNHOUSE_LOGFIRE_ENABLED=False',
  )

  if (config.aiEnabled && config.geminiApiKey) {
    lines.push(
      '',
      '# =============================================================================',
      '# AI Configuration',
      '# =============================================================================',
      '',
      `LEARNHOUSE_GEMINI_API_KEY=${quoteEnvValue(config.geminiApiKey)}`,
      'LEARNHOUSE_IS_AI_ENABLED=True',
    )
  } else {
    lines.push(
      '',
      '# =============================================================================',
      '# AI Configuration',
      '# =============================================================================',
      '',
      'LEARNHOUSE_IS_AI_ENABLED=False',
    )
  }

  if (config.emailEnabled) {
    const provider = config.emailProvider || 'resend'
    lines.push(
      '',
      '# =============================================================================',
      '# Email Configuration',
      '# =============================================================================',
      '',
      `LEARNHOUSE_EMAIL_PROVIDER=${provider}`,
      `LEARNHOUSE_SYSTEM_EMAIL_ADDRESS=${quoteEnvValue(config.systemEmailAddress || `noreply@${config.domain}`)}`,
    )

    if (provider === 'resend' && config.resendApiKey) {
      lines.push(`LEARNHOUSE_RESEND_API_KEY=${quoteEnvValue(config.resendApiKey)}`)
    }

    if (provider === 'smtp') {
      if (config.smtpHost) lines.push(`LEARNHOUSE_SMTP_HOST=${quoteEnvValue(config.smtpHost)}`)
      lines.push(`LEARNHOUSE_SMTP_PORT=${config.smtpPort || 587}`)
      if (config.smtpUsername) lines.push(`LEARNHOUSE_SMTP_USERNAME=${quoteEnvValue(config.smtpUsername)}`)
      if (config.smtpPassword) lines.push(`LEARNHOUSE_SMTP_PASSWORD=${quoteEnvValue(config.smtpPassword)}`)
      lines.push(`LEARNHOUSE_SMTP_USE_TLS=${config.smtpUseTls !== false ? 'True' : 'False'}`)
    }
  }

  if (config.s3Enabled && config.s3BucketName) {
    lines.push(
      '',
      '# =============================================================================',
      '# Content Delivery',
      '# =============================================================================',
      '',
      'LEARNHOUSE_CONTENT_DELIVERY_TYPE=s3api',
      `LEARNHOUSE_S3_API_BUCKET_NAME=${quoteEnvValue(config.s3BucketName)}`,
    )
    if (config.s3EndpointUrl) {
      lines.push(`LEARNHOUSE_S3_API_ENDPOINT_URL=${quoteEnvValue(config.s3EndpointUrl)}`)
    }
  } else {
    lines.push(
      '',
      '# =============================================================================',
      '# Content Delivery',
      '# =============================================================================',
      '',
      'LEARNHOUSE_CONTENT_DELIVERY_TYPE=filesystem',
    )
  }

  if (!config.useExternalDb) {
    lines.push(
      '',
      '# =============================================================================',
      '# Database Configuration',
      '# =============================================================================',
      '',
      'POSTGRES_USER=learnhouse',
      `POSTGRES_PASSWORD=${config.dbPassword}`,
      'POSTGRES_DB=learnhouse',
      '',
    )
  } else {
    lines.push('')
  }

  return lines.join('\n')
}
