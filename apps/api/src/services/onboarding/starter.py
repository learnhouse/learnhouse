def course_spec(goal: Optional[str]) -> dict:
    return COURSES.get(goal or "", _WELCOME)


def _now() -> str:
    return str(datetime.now())


async def create_starter_course(db_session: AsyncSession, org: Organization, user_id: int, goal: Optional[str]) -> Course:
    """The goal's starter course, as a private draft authored by ``user_id``."""
    from src.security.features_utils.usage import check_limits_with_usage, increase_feature_usage

    await check_limits_with_usage("courses", org.id, db_session)
    spec = course_spec(goal)
    course = Course(
        name=spec["name"],
        description=spec["description"],
        about=spec["description"],
        learnings="",
        tags="",
        thumbnail_type=ThumbnailType.IMAGE,
        thumbnail_image="",
        thumbnail_video="",
        public=False,
        published=False,
        open_to_contributors=False,
        org_id=org.id,
        course_uuid=f"course_{uuid4()}",
        creation_date=_now(),
        update_date=_now(),
    )
    db_session.add(course)
    await db_session.flush()
    db_session.add(ResourceAuthor(
        resource_uuid=course.course_uuid,
        user_id=user_id,
        authorship=ResourceAuthorshipEnum.CREATOR,
        authorship_status=ResourceAuthorshipStatusEnum.ACTIVE,
        creation_date=_now(),
        update_date=_now(),
    ))
    for c_order, chapter_spec in enumerate(spec["chapters"]):
        chapter = Chapter(
            name=chapter_spec["name"],
            description="",
            thumbnail_image="",
            org_id=org.id,
            course_id=course.id,
            chapter_uuid=f"chapter_{uuid4()}",
            creation_date=_now(),
            update_date=_now(),
        )
        db_session.add(chapter)
        await db_session.flush()
        db_session.add(CourseChapter(course_id=course.id, chapter_id=chapter.id, org_id=org.id, order=c_order, creation_date=_now(), update_date=_now()))
        for a_order, (title, blocks) in enumerate(chapter_spec["lessons"]):
            activity = Activity(
                name=title,
                activity_type=ActivityTypeEnum.TYPE_DYNAMIC,
                activity_sub_type=ActivitySubTypeEnum.SUBTYPE_DYNAMIC_PAGE,
                content=compile_document(blocks),
                published=True,
                org_id=org.id,
                course_id=course.id,
                activity_uuid=f"activity_{uuid4()}",
                creation_date=_now(),
                update_date=_now(),
            )
            db_session.add(activity)
            await db_session.flush()
            db_session.add(ChapterActivity(chapter_id=chapter.id, activity_id=activity.id, course_id=course.id, org_id=org.id, order=a_order, creation_date=_now(), update_date=_now()))
    await db_session.commit()
    await db_session.refresh(course)
    await increase_feature_usage("courses", org.id, db_session)
    return course


async def apply_website_template(db_session: AsyncSession, org: Organization, user: Any, template_id: str) -> str:
    """Publish the template as the org's home page. Returns the page uuid."""
    from src.services.landing import service as landing

    home = await landing.ensure_home(db_session, org, user)
    doc = await landing.template_for_org(db_session, org, template_id)
    clean = await landing._validated(db_session, org.id, doc)
    page = await landing.publish_doc(db_session, home, clean, landing._user_id(user), label="Starter template")
    return page.page_uuid


async def apply_starter(
    db_session: AsyncSession,
    org: Organization,
    user: Any,
    user_id: int,
    *,
    website: bool = True,
    course: bool = True,
) -> dict[str, Any]:
    """Apply the goal's starter once. A second call changes nothing."""
    row = await get_or_create(db_session, org)
    if "starter_applied" in (row.milestones or {}):
        raise HTTPException(status_code=409, detail="This organization already has its starter content")
    template_id = goal_defs.template_for(row.goal)
    result: dict[str, Any] = {"template": None, "page_uuid": None, "course_uuid": None}
    if website:
        result["template"] = template_id
        result["page_uuid"] = await apply_website_template(db_session, org, user, template_id)
    if course:
        try:
            result["course_uuid"] = (await create_starter_course(db_session, org, user_id, row.goal)).course_uuid
        except HTTPException as e:
            # The plan has no room for another course: the website still went
            # through, and the admin can make their own course later.
            logger.info("Starter course skipped for org %s: %s", org.id, e.detail)
    await db_session.refresh(row)
    stamp(row, "starter_applied")
    # The template made these, not the admin: nothing to celebrate yet.
    made = ({"create_course", "add_content"} if result["course_uuid"] else set()) | ({"share_grow"} if result["page_uuid"] else set())
    if made:
        row.state = {**(row.state or {}), "celebrated": sorted(set((row.state or {}).get("celebrated") or []) | made)}
    db_session.add(row)
    await db_session.commit()
    return result
