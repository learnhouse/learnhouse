#!/usr/bin/env node
// The SDK ships in lockstep with LearnHouse OSS releases: its version is the
// web app's version (apps/web/package.json). This copies that version into
// packages/sdk/package.json and src/version.ts.
//
//   node scripts/sync-version.mjs          write the version
//   node scripts/sync-version.mjs --check  exit 1 if either file has drifted

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const sdkDir = resolve(here, '..')
const repoRoot = resolve(sdkDir, '..', '..')

const webPkgPath = join(repoRoot, 'apps', 'web', 'package.json')
const sdkPkgPath = join(sdkDir, 'package.json')
const versionTsPath = join(sdkDir, 'src', 'version.ts')

const check = process.argv.includes('--check')

const target = JSON.parse(readFileSync(webPkgPath, 'utf8')).version
if (typeof target !== 'string' || !/^\d+\.\d+\.\d+(?:[-+][\w.+-]+)?$/.test(target)) {
  console.error(`[sync-version] apps/web/package.json has no usable version (got ${JSON.stringify(target)})`)
  process.exit(1)
}

const pkgText = readFileSync(sdkPkgPath, 'utf8')
const pkg = JSON.parse(pkgText)
const versionTs = [
  '// Generated by scripts/sync-version.mjs from apps/web/package.json. Do not edit.',
  `export const SDK_VERSION = '${target}'`,
  '',
].join('\n')

let currentVersionTs = ''
try {
  currentVersionTs = readFileSync(versionTsPath, 'utf8')
} catch {
  // missing file counts as drift
}

const drift = []
if (pkg.version !== target) drift.push(`package.json is ${pkg.version}`)
if (currentVersionTs !== versionTs) drift.push('src/version.ts is out of date')

if (check) {
  if (drift.length) {
    console.error(`[sync-version] SDK version drift (expected ${target}): ${drift.join('; ')}. Run \`bun run sync-version\`.`)
    process.exit(1)
  }
  console.log(`[sync-version] in sync at ${target}`)
  process.exit(0)
}

if (pkg.version !== target) {
  // Replace only the version field so the rest of the file keeps its formatting.
  const next = pkgText.replace(/("version"\s*:\s*)"[^"]*"/, `$1"${target}"`)
  writeFileSync(sdkPkgPath, next)
}
if (currentVersionTs !== versionTs) writeFileSync(versionTsPath, versionTs)
console.log(`[sync-version] SDK version set to ${target}`)
