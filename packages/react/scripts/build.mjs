#!/usr/bin/env node
// Builds @learnhouse/react from the LearnHouse web app's own source.
//
// Nothing under apps/web is copied. esbuild compiles the activity renderer and
// every block component straight out of apps/web, so a published package is
// exactly the renderer of the OSS release it is versioned with. Only the few
// Next.js and app-shell modules that cannot run inside someone else's React
// app are swapped for the shims in src/shims.
//
// Third-party imports stay external. Their versions are read from
// apps/web/package.json, so the package depends on what the web app ships.
import { build } from 'esbuild'
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import postcss from 'postcss'
import tailwind from '@tailwindcss/postcss'
import prefixSelector from 'postcss-prefix-selector'

const here = path.dirname(fileURLToPath(import.meta.url))
const pkgDir = path.resolve(here, '..')
const webDir = path.resolve(pkgDir, '../../apps/web')
const distDir = path.join(pkgDir, 'dist')
const cacheDir = path.join(pkgDir, '.cache')
const shims = path.join(pkgDir, 'src/shims')

export const SCOPE = '.lh-activity'

// Modules of the web app that are replaced in the package build.
export const SHIMS = {
  'next/image': `${shims}/next-image.tsx`,
  'next/link': `${shims}/next-link.tsx`,
  'next/dynamic': `${shims}/next-dynamic.tsx`,
  'next/navigation': `${shims}/next-navigation.ts`,
  // Session comes from <LearnHouseProvider>, not the app's auth flow.
  '@components/Contexts/AuthContext': `${shims}/auth-context.tsx`,
  // The app's analytics client (PostHog) becomes the onEvent callback.
  '@services/analytics': `${shims}/analytics.ts`,
  // Instance URLs come from the provider, not window.__RUNTIME_CONFIG__.
  '@services/config/config': `${shims}/config.ts`,
  // Per-renderer i18next instances with only the keys the blocks use.
  '@/lib/i18n': `${shims}/i18n.ts`,
  '@sentry/nextjs': `${shims}/sentry.ts`,
}

// Web files replaced however they are imported (alias or relative path). The
// app's analytics hook reaches PostHog; blocks import it from several places.
const SHIM_FILES = {
  'services/analytics/useLHAnalytics': `${shims}/analytics.ts`,
}
const shimForFile = (file) => {
  const rel = path.relative(webDir, file).replace(/\.(tsx?|jsx?)$/, '')
  return SHIM_FILES[rel]
}

const webAliases = Object.entries({
  '@components/': 'components/',
  '@public/': 'public/',
  '@images/': 'public/img/',
  '@styles/': 'styles/',
  '@services/': 'services/',
  '@editor/': 'components/Objects/Editor/',
  '@hooks/': 'components/Hooks/',
  '@lib/': 'lib/',
  '@ee/': 'ee-stub/',
  '@/': '',
  'app/': 'app/',
  'public/': 'public/',
})

function resolveWebPath(spec) {
  for (const [prefix, target] of webAliases) {
    if (spec.startsWith(prefix)) return path.join(webDir, target + spec.slice(prefix.length))
  }
  return null
}

const NODE_BUILTINS = new Set(['fs', 'path', 'os', 'crypto', 'url', 'util', 'stream', 'buffer'])

const packageName = (spec) =>
  spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0]

const sourcePlugin = {
  name: 'learnhouse-web-source',
  setup(b) {
    b.onResolve({ filter: /.*/ }, async (args) => {
      if (args.kind === 'entry-point') return
      const shim = SHIMS[args.path]
      if (shim) return { path: shim }
      const web = resolveWebPath(args.path)
      const target = web ?? (args.path.startsWith('.') ? path.resolve(args.resolveDir, args.path) : null)
      if (target && shimForFile(target)) return { path: shimForFile(target) }
      if (web) {
        // Let esbuild find the extension / index file inside the web tree.
        const r = await b.resolve('./' + path.basename(web), {
          resolveDir: path.dirname(web),
          kind: args.kind,
        })
        if (r.errors.length) return { errors: r.errors }
        return { path: r.path }
      }
      if (args.path.startsWith('.') || path.isAbsolute(args.path)) return
      if (args.path.startsWith('node:')) return { path: args.path, external: true }
      // Bare import: leave it to the consumer's bundler.
      return { path: args.path, external: true }
    })
  },
}

const LOCALES_DIR = path.join(pkgDir, 'src/generated')

async function writeLocalesModule(langs) {
  await mkdir(path.join(LOCALES_DIR, 'locales'), { recursive: true })
  const loaders = langs
    .filter((l) => l !== 'en')
    .map((l) => `  ${JSON.stringify(l)}: () => import('./locales/${l}.json'),`)
    .join('\n')
  await writeFile(
    path.join(LOCALES_DIR, 'locales.ts'),
    `// Generated by scripts/build.mjs from apps/web/locales. Do not edit.\n` +
      `import en from './locales/en.json'\n\n` +
      `export const EN: Record<string, any> = en\n\n` +
      `export const LOADERS: Record<string, () => Promise<{ default: Record<string, any> }>> = {\n${loaders}\n}\n`,
  )
}

const isObject = (v) => v && typeof v === 'object' && !Array.isArray(v)

/** Keys (or key prefixes) the bundled web source refers to, that exist in en.json. */
export function usedKeys(sources, en) {
  const exists = (key) => {
    let node = en
    for (const part of key.split('.')) {
      if (!isObject(node) || !(part in node)) return false
      node = node[part]
    }
    return true
  }
  const keys = new Set()
  for (const code of sources) {
    // Any dotted string literal that names a key or a subtree of keys.
    for (const m of code.matchAll(/['"`]([A-Za-z0-9_-]+(?:\.[A-Za-z0-9_-]+)+)['"`]/g)) {
      if (exists(m[1])) keys.add(m[1])
    }
    // Template keys like t(`editor.blocks.${type}`): keep the whole subtree.
    for (const m of code.matchAll(/`([A-Za-z0-9_-]+(?:\.[A-Za-z0-9_-]+)*)\.\$\{/g)) {
      if (exists(m[1])) keys.add(m[1])
    }
  }
  return keys
}

export function pickKeys(messages, keys) {
  const out = {}
  for (const key of keys) {
    const parts = key.split('.')
    const last = parts.pop()
    let src = messages
    let dst = out
    for (const part of parts) {
      if (!isObject(src?.[part])) { src = null; break }
      src = src[part]
      dst = dst[part] ??= {}
    }
    if (!src) continue
    for (const k of Object.keys(src)) {
      // Plural and context variants (count_one, count_other…) ride along.
      if (k === last || k.startsWith(`${last}_`)) dst[k] = src[k]
    }
  }
  return out
}

async function buildLocales(metafile) {
  // Web source, plus the package's own components (they reuse web keys).
  const srcDir = path.join(pkgDir, 'src')
  const webInputs = Object.keys(metafile.inputs)
    .map((f) => path.resolve(pkgDir, f))
    .filter((f) => (f.startsWith(webDir) || f.startsWith(srcDir)) && /\.(t|j)sx?$/.test(f))
  const sources = await Promise.all(webInputs.map((f) => readFile(f, 'utf8')))
  const localesDir = path.join(webDir, 'locales')
  const en = JSON.parse(await readFile(path.join(localesDir, 'en.json'), 'utf8'))
  const keys = usedKeys(sources, en)
  const { readdir } = await import('node:fs/promises')
  const langs = (await readdir(localesDir)).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort()
  let bytes = 0
  for (const lang of langs) {
    const messages = JSON.parse(await readFile(path.join(localesDir, `${lang}.json`), 'utf8'))
    const json = JSON.stringify(pickKeys(messages, keys))
    bytes += json.length
    await writeFile(path.join(LOCALES_DIR, 'locales', `${lang}.json`), json)
  }
  await writeLocalesModule(langs)
  return { keys: keys.size, langs: langs.length, bytes }
}

async function buildJs({ write = true } = {}) {
  const result = await build({
    write,
    // index: the React component. element: the same component as a custom
    // element (<learnhouse-activity>) for non-React apps. They share chunks.
    entryPoints: [path.join(pkgDir, 'src/index.ts'), path.join(pkgDir, 'src/element.tsx')],
    outdir: distDir,
    bundle: true,
    splitting: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    charset: 'utf8',
    jsx: 'automatic',
    minify: true,
    sourcemap: true,
    metafile: true,
    chunkNames: 'chunks/[name]-[hash]',
    loader: { '.png': 'dataurl', '.jpg': 'dataurl', '.svg': 'dataurl', '.gif': 'dataurl', '.webp': 'dataurl' },
    define: {
      // Web code reads these at module scope; the consumer's bundler or the
      // provider supplies real values at runtime.
      'process.env.NEXT_PUBLIC_LEARNHOUSE_BACKEND_URL': 'undefined',
      'process.env.NEXT_PUBLIC_LEARNHOUSE_API_URL': 'undefined',
    },
    banner: { js: '"use client";' },
    // 'use client' directives inside web modules are meaningless once bundled.
    logOverride: { 'unsupported-directive': 'silent' },
    plugins: [sourcePlugin],
  })
  return result.metafile
}

/** Packages only a compiler reads; never a runtime dependency of dist/. */
export function isBuildOnly(name) {
  return name === 'typescript' || name.startsWith('@types/')
}

/** Third-party packages the bundle imports, with the versions apps/web pins. */
export async function externalDependencies(metafile) {
  const webPkg = JSON.parse(await readFile(path.join(webDir, 'package.json'), 'utf8'))
  const webDeps = { ...webPkg.devDependencies, ...webPkg.dependencies }
  const names = new Set()
  for (const output of Object.values(metafile.outputs)) {
    for (const imp of output.imports) {
      if (imp.external && !imp.path.startsWith('node:')) names.add(packageName(imp.path))
    }
  }
  const deps = {}
  const missing = []
  for (const name of [...names].sort()) {
    if (name === 'react' || name === 'react-dom') continue
    if (name === '@learnhouse/sdk') continue
    // Server-only branches of the web config (runtime-config.json on disk).
    if (NODE_BUILTINS.has(name)) continue
    if (webDeps[name]) {
      deps[name] = webDeps[name]
      continue
    }
    // Imported by web source but only installed transitively (e.g. a
    // @codemirror package that @uiw/react-codemirror brings): pin what the
    // web app actually resolves.
    const installed = path.join(webDir, 'node_modules', name, 'package.json')
    if (existsSync(installed)) deps[name] = `^${JSON.parse(await readFile(installed, 'utf8')).version}`
    else missing.push(name)
  }
  // Peers of those packages that the web app installs too (@videojs/react's
  // optional HLS adapter, @tiptap/pm…): consumers need the same pairs.
  // Type packages and the compiler are peers too (i18next wants typescript,
  // @tiptap/react wants @types/react) but nothing loads them at runtime, so
  // they stay out: TypeScript users already have their own.
  for (const name of Object.keys(deps)) {
    const manifest = path.join(webDir, 'node_modules', name, 'package.json')
    if (!existsSync(manifest)) continue
    const { peerDependencies = {} } = JSON.parse(await readFile(manifest, 'utf8'))
    for (const peer of Object.keys(peerDependencies)) {
      if (peer === 'react' || peer === 'react-dom' || isBuildOnly(peer)) continue
      if (webDeps[peer] && !deps[peer]) deps[peer] = webDeps[peer]
    }
  }
  return { deps: Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b))), missing }
}

async function buildCss() {
  // The package stylesheet is the web app's own globals.css, compiled by the
  // same Tailwind setup, with class scanning narrowed to what the renderer
  // ships and every rule scoped under SCOPE so it can't touch the host page.
  const globals = await readFile(path.join(webDir, 'styles/globals.css'), 'utf8')
  const sources = [
    'components/Objects/Activities',
    'components/Objects/Editor/Extensions',
    'components/Objects/StyledElements',
    'components/Contexts',
    'lib',
    'services',
    // Learner-side assignment task editors (rendered for signed-in learners).
    'app/orgs/[orgslug]/dash/assignments/[assignmentuuid]/_components/TaskEditor/Subs/TaskTypes',
  ].map((dir) => `@source '${path.join(webDir, dir)}';`)
  const input = globals
    .replace(/@import ['"]tailwindcss['"];/, `@import 'tailwindcss' source(none);\n${sources.join('\n')}\n@source '${path.join(pkgDir, 'src')}';`)
    .replace(/@source ['"]\.\.\/ee['"];/, '')
    .replace(/@import ["']\.\/(mobile[^"']*\.css)["'];/g, (_m, file) => `@import '${path.join(webDir, 'styles', file)}';`)
  await mkdir(cacheDir, { recursive: true })
  const from = path.join(cacheDir, 'globals.css')
  await writeFile(from, input)

  const scope = (prefix, selector, prefixed) => {
    if (selector === ':root' || selector === ':host' || selector === 'html' || selector === 'body' || selector === 'html, body' || selector === ':root, :host') return prefix
    if (/^(html|body|:root)\b/.test(selector)) return selector.replace(/^(html|body|:root)/, prefix)
    if (selector.startsWith('.dark ')) return `${prefix}.dark ${selector.slice(6)}`
    return prefixed
  }
  const result = await postcss([
    tailwind({ base: webDir, optimize: { minify: true } }),
    prefixSelector({ prefix: SCOPE, transform: scope, exclude: [/^@/, /keyframes/, /^from$/, /^to$/, /^\d+%$/] }),
  ]).process(input, { from, to: path.join(distDir, 'styles.css') })
  await writeFile(path.join(distDir, 'styles.css'), result.css)
  return result.css.length
}

async function buildTypes() {
  execFileSync(path.join(pkgDir, 'node_modules/.bin/tsc'), ['-p', path.join(pkgDir, 'tsconfig.build.json')], {
    stdio: 'inherit',
  })
  await writeFile(path.join(distDir, 'index.d.ts'), "export * from './types/public'\n")
  await writeFile(path.join(distDir, 'element.d.ts'), "export * from './types/element-public'\n")
}

async function main() {
  await rm(distDir, { recursive: true, force: true })
  // Pass 1 finds which web modules the renderer pulls in, so pass 2 can ship
  // only the translation keys those modules use.
  await mkdir(path.join(LOCALES_DIR, 'locales'), { recursive: true })
  await writeFile(path.join(LOCALES_DIR, 'locales', 'en.json'), '{}')
  await writeLocalesModule(['en'])
  const probe = await buildJs({ write: false })
  const locales = await buildLocales(probe)
  console.log(`locales: ${locales.langs} languages, ${locales.keys} keys, ${(locales.bytes / 1024).toFixed(1)} KB`)
  const metafile = await buildJs()
  await mkdir(cacheDir, { recursive: true })
  await writeFile(path.join(cacheDir, 'metafile.json'), JSON.stringify(metafile))
  const { deps, missing } = await externalDependencies(metafile)
  if (missing.length) {
    throw new Error(`Bundle imports packages apps/web does not declare: ${missing.join(', ')}`)
  }
  const cssBytes = await buildCss()
  // The renderer root's own rules are scoped already; append them unprefixed.
  const rootCss = await readFile(path.join(pkgDir, 'src/index.css'), 'utf8')
  const { appendFile } = await import('node:fs/promises')
  await appendFile(path.join(distDir, 'styles.css'), `\n${rootCss}`)
  // CSS that web components import themselves (the video player's) lands next
  // to the JS; fold it into the one stylesheet consumers import.
  for (const [file] of Object.entries(metafile.outputs)) {
    if (!file.endsWith('.css')) continue
    const abs = path.resolve(pkgDir, file)
    await appendFile(path.join(distDir, 'styles.css'), `\n${await readFile(abs, 'utf8')}`)
    await rm(abs)
    await rm(`${abs}.map`, { force: true })
  }
  await buildTypes()

  const js = Object.entries(metafile.outputs).filter(([f]) => f.endsWith('.js'))
  const entry = js.find(([f]) => f.endsWith('dist/index.js'))
  const element = js.find(([f]) => f.endsWith('dist/element.js'))
  console.log(`js: ${js.length} files, entry ${(entry[1].bytes / 1024).toFixed(1)} KB, element ${(element[1].bytes / 1024).toFixed(1)} KB, total ${(js.reduce((n, [, o]) => n + o.bytes, 0) / 1024).toFixed(1)} KB`)
  console.log(`css: ${(cssBytes / 1024).toFixed(1)} KB`)
  console.log(`external deps: ${Object.keys(deps).length}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!existsSync(webDir)) throw new Error(`apps/web not found at ${webDir}`)
  main().catch((error) => {
    console.error(error)
    process.exit(1)
  })
}
